<?php

declare(strict_types=1);

namespace TMSWP\AcfBridge\Cli;

use Closure;
use FilesystemIterator;
use SplFileInfo;
use TMSWP\AcfBridge\BridgeConfig;
use TMSWP\AcfBridge\Exception\AcfBridgeException;
use TMSWP\AcfBridge\Exception\AcfBridgeRuntimeException;
use TMSWP\AcfBridge\Generate\GeneratedFile;
use TMSWP\AcfBridge\Generate\Generator;
use TMSWP\AcfBridge\Generate\GeneratorContext;
use TMSWP\AcfBridge\Generate\Report;
use TMSWP\AcfBridge\Json\AcfJsonRepository;
use TMSWP\AcfBridge\Json\FieldGroup;
use TMSWP\AcfBridge\Mapping\LocationResolver;

/**
 * acf-jsonからの生成と、outputDirとの照合・書き込み(sync・check)。WordPressを使わず、WP-CLIの
 * `wp tmswp acf`とWordPressを起動しない`tms-acf`が、同じこの処理を使う。終了コードは次のとおり
 * (sync: 0成功 / 1 E* または書き込みの失敗 / 2環境・設定の誤り、check: 0差分なし / 1差分あり、
 * または--strictでW* あり / 2 E* または環境・設定の誤り)。E*・W*のコードの意味は、tmswp/acf-bridgeのレシピ
 * rules/sync-check.mdの表にある。
 *
 * @internal AcfCommandとtms-acfだけが使う
 */
final class SyncRunner
{
    private const GENERATED_MARKER = '@generated by tmswp/acf-bridge';

    /** checkが「modified」のファイルごとに表示する、統一diffの行数の上限 */
    private const int DIFF_LINES = 40;

    /** 統一diffの前後の文脈の行数 */
    private const int DIFF_CONTEXT = 3;

    /**
     * $conflictErrorsは、E101(#[MetaSchema]との重複)のエラーを返す関数。WordPressの実行時(起動中のKernelのレジストリ)が
     * 要るため、WP-CLI版だけが渡す。
     *
     * @param (Closure(BridgeConfig, list<FieldGroup>): list<string>)|null $conflictErrors
     */
    public function __construct(private readonly ?Closure $conflictErrors = null) {}

    /**
     * acf-jsonから生成し、outputDirへ書き込む(dryRunなら差分を表示するだけ)。
     *
     * @return array{lines: list<string>, status: int, message: string}
     */
    public function sync(BridgeConfig $config, bool $dryRun): array
    {
        try {
            $result = $this->generate($config);
        } catch (AcfBridgeException $exception) {
            return ['lines' => [$exception->getMessage()], 'status' => 2, 'message' => ''];
        }

        $lines = $this->diagnostics($result['report']);

        try {
            $lines = [...$lines, ...$this->unmarkedFileLines($config, $result['report'])];

            if ($result['report']->hasErrors()) {
                return ['lines' => [...$lines, 'ACF bridge generation failed'], 'status' => 1, 'message' => ''];
            }

            if ($dryRun) {
                return ['lines' => [...$lines, ...$this->differenceLines($this->differences($config, $result['report']))], 'status' => 0, 'message' => 'ACF bridge sync dry-run completed'];
            }

            $lines = [...$lines, ...$this->writeGeneratedFiles($config, $result['report']), ...$this->deleteOrphans($config, $result['report'])];
        } catch (AcfBridgeRuntimeException $exception) {
            return ['lines' => [...$lines, $exception->getMessage()], 'status' => 1, 'message' => ''];
        }

        return ['lines' => $lines, 'status' => 0, 'message' => 'ACF bridge sync completed'];
    }

    /**
     * acf-jsonから生成した内容とoutputDirを照合する。
     *
     * @return array{lines: list<string>, status: int, message: string}
     */
    public function check(BridgeConfig $config, bool $strict): array
    {
        try {
            $result = $this->generate($config);
        } catch (AcfBridgeException $exception) {
            return ['lines' => [$exception->getMessage()], 'status' => 2, 'message' => ''];
        }

        $lines = $this->diagnostics($result['report']);

        try {
            $lines = [...$lines, ...$this->unmarkedFileLines($config, $result['report'])];

            if ($result['report']->hasErrors()) {
                return ['lines' => [...$lines, 'ACF bridge generation failed'], 'status' => 2, 'message' => ''];
            }

            $diffs = $this->differences($config, $result['report']);
        } catch (AcfBridgeRuntimeException $exception) {
            return ['lines' => [...$lines, $exception->getMessage()], 'status' => 2, 'message' => ''];
        }

        if ($diffs !== []) {
            return ['lines' => [...$lines, ...$this->differenceLines($diffs), 'Run: composer acf:sync (vendor/bin/tms-acf sync or wp tmswp acf sync)'], 'status' => 1, 'message' => ''];
        }

        if ($strict && $result['report']->warnings() !== []) {
            return ['lines' => [...$lines, 'ACF bridge strict check failed with warnings'], 'status' => 1, 'message' => ''];
        }

        return [
            'lines' => $lines,
            'status' => 0,
            'message' => 'ACF bridge is in sync. (' . \count($result['report']->files()) . ' files, source-hash sha256:' . $result['sourceHash'] . ')',
        ];
    }

    /**
     * @throws AcfBridgeException acf-jsonの読み込みの失敗、オプションページのpost_idの指定の食い違い
     *
     * @return array{report: Report, sourceHash: string}
     */
    private function generate(BridgeConfig $config): array
    {
        $json = (new AcfJsonRepository($config->jsonDirs))->load();
        $report = (new Generator(new LocationResolver()))->generate(
            $json->fieldGroups,
            new GeneratorContext(
                config: $config,
                optionsPagePostIds: $this->optionsPagePostIds($json->optionsPagePostIds, $config),
                sourceHash: $json->sourceHash,
            ),
        );
        $conflictErrors = $this->conflictErrors === null ? [] : ($this->conflictErrors)($config, $json->fieldGroups);

        return [
            'report' => new Report(
                $report->files(),
                [...$report->errors(), ...$conflictErrors],
                [...$json->warnings, ...$report->warnings()],
            ),
            'sourceHash' => $json->sourceHash,
        ];
    }

    /**
     * オプションページのmenu_slug => post_id。acf-jsonのui_options_pageのpost_idと、BridgeConfigの
     * optionsPagePostIdsを合わせる(ACFの実行時には問い合わせない。生成結果を環境に依存させないため)。
     *
     * @param array<string, string> $postIds acf-jsonのui_options_pageのmenu_slug => post_id
     *
     * @throws AcfBridgeRuntimeException 同じページに違うpost_idを指定した場合
     *
     * @return array<string, string>
     */
    private function optionsPagePostIds(array $postIds, BridgeConfig $config): array
    {

        foreach ($config->optionsPagePostIds as $menuSlug => $postId) {
            if (\array_key_exists($menuSlug, $postIds) && $postIds[$menuSlug] !== $postId) {
                throw new AcfBridgeRuntimeException("E102: options page '{$menuSlug}' has post_id '{$postIds[$menuSlug]}' in acf-json and '{$postId}' in BridgeConfig optionsPagePostIds");
            }

            $postIds[$menuSlug] = $postId;
        }

        ksort($postIds, SORT_STRING);

        return $postIds;
    }

    /**
     * 生成した内容とoutputDirの差。modifiedは、今のファイルから生成した内容への統一diffの先頭DIFF_LINES行を持つ。
     *
     * @throws AcfBridgeRuntimeException 生成物のファイル、またはoutputDirのPHPファイルを読めない場合
     *
     * @return list<array{type: string, path: string, diff: list<string>}>
     */
    private function differences(BridgeConfig $config, Report $report): array
    {
        $diffs = [];
        $expected = [];

        foreach ($report->files() as $file) {
            $expected[$file->relativePath] = true;
            $path = $this->pathFor($config, $file);

            if (!is_file($path)) {
                $diffs[] = ['type' => 'missing', 'path' => $file->relativePath, 'diff' => []];
                continue;
            }

            $contents = file_get_contents($path);

            if ($contents === false) {
                throw new AcfBridgeRuntimeException("E102: failed to read generated file {$path}");
            }

            if ($contents !== $file->contents) {
                $diffs[] = ['type' => 'modified', 'path' => $file->relativePath, 'diff' => $this->unifiedDiff($file->relativePath, $contents, $file->contents)];
            }
        }

        foreach ($this->generatedPhpFiles($config) as $path) {
            $relativePath = basename($path);

            if (!\array_key_exists($relativePath, $expected) && $this->hasGeneratedMarker($path)) {
                $diffs[] = ['type' => 'orphan', 'path' => $relativePath, 'diff' => []];
            }
        }

        return $diffs;
    }

    /**
     * @throws AcfBridgeRuntimeException 出力先の作成・書き込みに失敗した場合
     *
     * @return list<string>
     */
    private function writeGeneratedFiles(BridgeConfig $config, Report $report): array
    {
        if (!is_dir($config->outputDir) && !mkdir($config->outputDir, 0775, true) && !is_dir($config->outputDir)) {
            throw new AcfBridgeRuntimeException("E102: failed to create output directory {$config->outputDir}");
        }

        $lines = [];

        foreach ($report->files() as $file) {
            $path = $this->pathFor($config, $file);
            $tmp = $path . '.tmp';

            if (file_put_contents($tmp, $file->contents) === false) {
                throw new AcfBridgeRuntimeException("E102: failed to write generated file {$tmp}");
            }

            if (!rename($tmp, $path)) {
                throw new AcfBridgeRuntimeException("E102: failed to move generated file {$tmp} to {$path}");
            }

            $lines[] = "write: {$file->relativePath}";
        }

        return $lines;
    }

    /**
     * @throws AcfBridgeRuntimeException 孤児の削除に失敗した場合、outputDirのPHPファイルを読めない場合
     *
     * @return list<string>
     */
    private function deleteOrphans(BridgeConfig $config, Report $report): array
    {
        $expected = [];
        $lines = [];

        foreach ($report->files() as $file) {
            $expected[$file->relativePath] = true;
        }

        foreach ($this->generatedPhpFiles($config) as $path) {
            $relativePath = basename($path);

            if (\array_key_exists($relativePath, $expected) || !$this->hasGeneratedMarker($path)) {
                continue;
            }

            if (!unlink($path)) {
                throw new AcfBridgeRuntimeException("E102: failed to delete orphan generated file {$relativePath}");
            }

            $lines[] = "delete: {$relativePath}";
        }

        return $lines;
    }

    /** @return list<string> */
    private function generatedPhpFiles(BridgeConfig $config): array
    {
        if (!is_dir($config->outputDir)) {
            return [];
        }

        $files = [];
        $iterator = new FilesystemIterator($config->outputDir, FilesystemIterator::SKIP_DOTS);

        foreach ($iterator as $fileInfo) {
            if (!$fileInfo instanceof SplFileInfo || !$fileInfo->isFile() || $fileInfo->getExtension() !== 'php') {
                continue;
            }

            $files[] = $fileInfo->getPathname();
        }

        sort($files, SORT_STRING);

        return $files;
    }

    /**
     * outputDirのPHPファイルが@generatedのマーカーを持つか(生成物か)。読めないファイルは、マーカーの有無を決められない
     * ため、手書きのファイル(I002)とも孤児ともみなさず例外にする。
     *
     * @throws AcfBridgeRuntimeException ファイルを読めない場合
     */
    private function hasGeneratedMarker(string $path): bool
    {
        $contents = is_readable($path) ? file_get_contents($path) : false;

        if ($contents === false) {
            throw new AcfBridgeRuntimeException("E102: failed to read {$path} in outputDir to check the @generated marker; fix the file permissions or remove the file");
        }

        return str_contains($contents, self::GENERATED_MARKER);
    }

    private function pathFor(BridgeConfig $config, GeneratedFile $file): string
    {
        return rtrim($config->outputDir, DIRECTORY_SEPARATOR) . DIRECTORY_SEPARATOR . $file->relativePath;
    }

    /** @return list<string> */
    private function diagnostics(Report $report): array
    {
        return [...$report->errors(), ...$report->warnings()];
    }

    /**
     * @param list<array{type: string, path: string, diff: list<string>}> $diffs
     *
     * @return list<string>
     */
    private function differenceLines(array $diffs): array
    {
        $lines = [];

        foreach ($diffs as $diff) {
            $lines = [...$lines, $diff['type'] . ': ' . $diff['path'], ...$diff['diff']];
        }

        return $lines;
    }

    /**
     * I002: outputDirにある、期待する生成物でなく@generatedのマーカーも無いPHPファイル(利用者のファイル)。syncは
     * 削除しない。
     *
     * @throws AcfBridgeRuntimeException outputDirのPHPファイルを読めない場合
     *
     * @return list<string>
     */
    private function unmarkedFileLines(BridgeConfig $config, Report $report): array
    {
        $expected = [];

        foreach ($report->files() as $file) {
            $expected[$file->relativePath] = true;
        }

        $lines = [];

        foreach ($this->generatedPhpFiles($config) as $path) {
            $relativePath = basename($path);

            if (!\array_key_exists($relativePath, $expected) && !$this->hasGeneratedMarker($path)) {
                $lines[] = "I002: {$relativePath} in {$config->outputDir} has no @generated marker; it is not a generated file and was not deleted";
            }
        }

        return $lines;
    }

    /**
     * 今のファイルの内容$currentから生成した内容$expectedへの統一diff(1つのhunk。前後で一致する行を除いた間を
     * 置き換えとし、前後に文脈の行を付ける)の、先頭DIFF_LINES行。
     *
     * @return list<string>
     */
    private function unifiedDiff(string $relativePath, string $current, string $expected): array
    {
        $old = self::lines($current);
        $new = self::lines($expected);
        $oldCount = \count($old);
        $newCount = \count($new);
        $prefix = 0;

        while ($prefix < $oldCount && $prefix < $newCount && $old[$prefix] === $new[$prefix]) {
            ++$prefix;
        }

        $suffix = 0;

        while ($suffix < $oldCount - $prefix && $suffix < $newCount - $prefix && $old[$oldCount - 1 - $suffix] === $new[$newCount - 1 - $suffix]) {
            ++$suffix;
        }

        $start = max(0, $prefix - self::DIFF_CONTEXT);
        $trailing = min(self::DIFF_CONTEXT, $suffix);
        $oldLength = $oldCount - $suffix + $trailing - $start;
        $newLength = $newCount - $suffix + $trailing - $start;
        $lines = [
            "--- a/{$relativePath}",
            "+++ b/{$relativePath}",
            '@@ -' . ($oldLength === 0 ? $start : $start + 1) . ",{$oldLength} +" . ($newLength === 0 ? $start : $start + 1) . ",{$newLength} @@",
        ];

        for ($i = $start; $i < $prefix; ++$i) {
            array_push($lines, ...self::diffLine(' ', $old[$i]));
        }

        for ($i = $prefix; $i < $oldCount - $suffix; ++$i) {
            array_push($lines, ...self::diffLine('-', $old[$i]));
        }

        for ($i = $prefix; $i < $newCount - $suffix; ++$i) {
            array_push($lines, ...self::diffLine('+', $new[$i]));
        }

        for ($i = $oldCount - $suffix; $i < $oldCount - $suffix + $trailing; ++$i) {
            array_push($lines, ...self::diffLine(' ', $old[$i]));
        }

        return \array_slice($lines, 0, self::DIFF_LINES);
    }

    /**
     * 統一diffの1行。改行で終わらない行(ファイルの最終行で、末尾に改行が無いもの)には、標準の注記
     * `\ No newline at end of file`の行を続ける。
     *
     * @return list<string>
     */
    private static function diffLine(string $mark, string $line): array
    {
        return str_ends_with($line, "\n")
            ? [$mark . substr($line, 0, -1)]
            : [$mark . $line, '\\ No newline at end of file'];
    }

    /**
     * 内容の行。各行は末尾の改行を含めて持つため、最終行に改行があるかどうかの差も行の差として比べる。
     *
     * @return list<string>
     */
    private static function lines(string $contents): array
    {
        $parts = explode("\n", $contents);
        $last = array_pop($parts);
        $lines = array_map(static fn(string $line): string => $line . "\n", $parts);

        if ($last !== '') {
            $lines[] = $last;
        }

        return $lines;
    }
}
