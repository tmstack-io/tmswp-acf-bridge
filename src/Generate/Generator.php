    /**
     * @param list<FieldGroup> $groups
     */
    public function generate(array $groups, GeneratorContext $context): Report
    {
        $errors = [];
        $warnings = [];
        $groups = (new CloneResolver())->resolve($groups, $errors);
        $buckets = $this->buckets($groups, $context->config, $errors, $warnings);
        $files = [];

        foreach ($buckets as $bucket) {
            $imports = new ClassImports($bucket->target->className);
            $accessors = $this->accessorsFor($bucket, $context->config, $imports, $errors, $warnings);
            $files[] = new GeneratedFile(
                $bucket->target->className . '.php',
                $this->renderClass($bucket, $accessors, $context, $imports),
            );

            // flexible_contentのレイアウトの型の別名は、クラスの中で一意に宣言できなければならない
            foreach ($imports->localAliasConflicts() as $conflict) {
                $errors[] = "E002: class {$bucket->target->className} cannot declare the layout type aliases of flexible_content fields: {$conflict}; rename the flexible_content field or the layout in ACF";
            }
        }

        $files[] = new GeneratedFile('AcfManifest.php', $this->renderManifest($groups, $context));

        usort($files, static fn(GeneratedFile $a, GeneratedFile $b): int => $a->relativePath <=> $b->relativePath);

        return new Report($files, $errors, $warnings);
    }

    /**
     * @param list<FieldGroup> $groups
     * @param list<string> $errors
     * @param list<string> $warnings
     *
     * @return list<TargetBucket>
     */
    private function buckets(array $groups, BridgeConfig $config, array &$errors, array &$warnings): array
    {
        /** @var array<string, TargetBucket> $buckets */
        $buckets = [];
        /** @var array<string, string> $classTargets */
        $classTargets = [];
        $placed = [];

        foreach ($groups as $group) {
            if (!$group->active) {
                $warnings[] = "W011: inactive ACF field group '{$group->key}' was skipped";
                continue;
            }

            $targets = $this->locations->resolveWithWarnings($group, $config, $warnings);

            if ($targets === []) {
                $warnings[] = "W002: ACF field group '{$group->key}' location could not be resolved";
                continue;
            }

            // テンプレート別のクラスは、投稿タイプごとの対象が1つのクラスになるため、クラスを分けるキーで数える
            $classKeys = array_unique(array_map(static fn(GenerationTarget $target): string => $target->key(), $targets));

            if (\count($classKeys) > 1 && \array_key_exists($group->key, $config->classMap)) {
                $errors[] = "E003: classMap for '{$group->key}' is only allowed for a group whose location resolves to one class";
                continue;
            }

            foreach ($targets as $target) {
                $targetKey = $this->targetKey($target);

                if (!$this->isClassName($target->className)) {
                    $errors[] = "E003: target {$targetKey} resolves to invalid class name '{$target->className}'";
                    continue;
                }

                $existing = $buckets[$targetKey] ?? null;

                // 1つの生成のキーは1つのクラスになるため、classMapで違うクラス名を求めるグループがあれば設定の誤り
                if ($existing instanceof TargetBucket && $existing->target->className !== $target->className) {
                    $errors[] = "E003: target {$targetKey} is requested as class '{$existing->target->className}' by group '{$existing->groups()[0]->key}' and as class '{$target->className}' by group '{$group->key}'; set the same class name for both groups in BridgeConfig::\$classMap (one class is generated per target)";
                    continue;
                }

                $registeredTarget = $classTargets[$target->className] ?? null;

                if ($registeredTarget !== null && $registeredTarget !== $targetKey) {
                    $errors[] = "E003: class name '{$target->className}' is used by both {$registeredTarget} and {$targetKey}; set another class name for the group of one of them in BridgeConfig::\$classMap (only for a group whose location resolves to one class)";
                    continue;
                }

                $classTargets[$target->className] = $targetKey;
                $buckets[$targetKey] ??= new TargetBucket($target);

                // テンプレート別のクラスは、同じグループが投稿タイプごとの対象から同じクラスに入るため、1回だけ足す
                if (!\in_array($group, $buckets[$targetKey]->groups(), true)) {
                    $buckets[$targetKey]->addGroup($group);
                }

                $placed[] = [$group, $target];
            }
        }

        $errors = [...$errors, ...$this->templateFieldConflicts($placed)];
        ksort($buckets, SORT_STRING);

        return array_values($buckets);
    }

    /**
     * テンプレート別のクラスとその投稿タイプのクラス(PageFields等。`post_type==all`のクラスも、どの投稿タイプにも重なる)
     * が、同じ名前の別のフィールド(field keyが違う)を持てばE001にする。テンプレートを選んだ投稿には両方のグループが表示され、ACFはどちらも同じ投稿のメタ(その名前)に保存する
     * ため、2つのフィールドが1つのメタを奪い合う。field keyが同じなら同じフィールド(cloneで共有したもの等)で、衝突しない。
     *
     * @param list<array{FieldGroup, GenerationTarget}> $placed クラスに入れたグループと、その対象
     *
     * @return list<string>
     */
    private function templateFieldConflicts(array $placed): array
    {
        $plain = [];
        $templated = [];

        foreach ($placed as [$group, $target]) {
            if ($target->kind !== TargetKind::Post) {
                continue;
            }

            foreach ($group->fields as $field) {
                if (!$this->types->storesValue($field) || $field->name === '') {
                    continue;
                }

                if ($target->template === null) {
                    $plain[$field->name][] = [$target->subtype, $field->key, $group->key];
                } else {
                    $templated[] = [$target, $field->name, $field->key, $group->key];
                }
            }
        }

        $errors = [];

        foreach ($templated as [$target, $name, $fieldKey, $groupKey]) {
            foreach ($plain[$name] ?? [] as [$plainSubtype, $plainFieldKey, $plainGroupKey]) {
                $overlaps = $plainSubtype === $target->subtype || $plainSubtype === 'all' || $target->subtype === 'all';

                if ($overlaps && $plainFieldKey !== $fieldKey) {
                    $errors[] = "E001: duplicate ACF field '{$name}' for post:{$plainSubtype} in groups {$plainGroupKey} and {$groupKey} (template '{$target->template}' of post:{$target->subtype}); a post with the template shows both groups and ACF saves both fields to the same meta key, so rename one of them or share one field";
                }
            }
        }

        return array_values(array_unique($errors));
    }

    /**
     * @param list<string> $errors
     * @param list<string> $warnings
     *
     * @return list<AccessorDefinition>
     */
    private function accessorsFor(TargetBucket $bucket, BridgeConfig $config, ClassImports $imports, array &$errors, array &$warnings): array
    {
        $accessors = [];
        /** @var array<string, string> $fieldNames */
        $fieldNames = [];
        $methods = $this->reservedMethods();
        /** @var array<string, string> $constants */
        $constants = [];

        foreach ($bucket->groups() as $group) {
            foreach ($group->fields as $field) {
                if (!$this->types->storesValue($field)) {
                    continue;
                }

                $registeredGroup = $fieldNames[$field->name] ?? null;

                if ($registeredGroup !== null) {
                    $errors[] = "E001: duplicate ACF field '{$field->name}' for {$this->targetKey($bucket->target)} in groups {$registeredGroup} and {$group->key}";
                    continue;
                }

                $fieldNames[$field->name] = $group->key;

                if (!$this->checkValueField($field, $field->name, $group->key, $errors, $warnings)) {
                    continue;
                }

                $accessor = $this->accessorFor($group, $field, $config, $imports, $methods, $constants, $errors, $warnings);

                if ($accessor instanceof AccessorDefinition) {
                    $accessors[] = $accessor;
                }
            }
        }

        return $accessors;
    }

    /**
     * 生成するメソッドと衝突してはいけないメソッド名(小文字 => 説明)。AcfFieldAccessのメソッド(private・protected・
     * publicのすべて)は、traitを変えても漏れないようにReflectionで集める。PHPのメソッド名は大文字小文字を区別しない
     * ため、小文字で照合する。
     *
     * @return array<string, string>
     */
    private function reservedMethods(): array
    {
        $methods = [];

        foreach ((new ReflectionClass(AcfFieldAccess::class))->getMethods() as $method) {
            $methods[strtolower($method->getName())] = "the method '{$method->getName()}' of the trait AcfFieldAccess";
        }

        foreach (self::FACTORY_METHODS as $factory) {
            $methods[strtolower($factory)] = "the factory method '{$factory}' of the generated class";
        }

        return $methods;
    }

    /**
     * フィールドの型を検査する。未知の型はW005(入れ子のサブフィールドも)。group・repeater・flexible_contentの
     * サブフィールドの名前の重複と、flexible_contentのレイアウトのacf_fc_layoutという名前のサブフィールドは、生成する
     * 配列のキーが重なるためE002にしてfalseを返す。flexible_contentのレイアウトの名前の重複と、PHPが整数のキーにする
     * レイアウトの名前も、生成するレイアウトごとの配列のキーにできないためE002にしてfalseを返す。サブフィールドと
     * レイアウトの名前は生成するgetterのPHPDocの型(shapeのキー・レイアウトのリテラル)になるため、docコメントを閉じる
     * 並び(アスタリスクとスラッシュ)を含む名前もE002にしてfalseを返す。
     *
     * @param string $path 警告とエラーに出すフィールドの位置(`stores.shop_name`の形)
     * @param list<string> $errors
     * @param list<string> $warnings
     */
    private function checkValueField(FieldDefinition $field, string $path, string $groupKey, array &$errors, array &$warnings): bool
    {
        if (!\in_array($field->type, self::KNOWN_FIELD_TYPES, true)) {
            $warnings[] = "W005: unknown ACF field type '{$field->type}' for '{$path}' was generated as mixed";
        }

        $valid = true;

        if (\in_array($field->type, ['group', 'repeater'], true)) {
            $valid = $this->checkSubFields($field->subFields, $path, $groupKey, null, $errors, $warnings);
        }

        if ($field->type === 'flexible_content') {
            $layoutNames = [];

            foreach ($field->layouts as $layout) {
                // 生成する`レイアウトの名前 => 正規化の関数`の配列のキーになるため、PHPが整数にする名前は文字列のキーで持てない
                if (\is_int(array_key_first([$layout->name => true]))) {
                    $errors[] = "E002: ACF field '{$path}' in group '{$groupKey}' has a layout named '{$layout->name}', which PHP converts to the integer array key {$layout->name}, so the generated accessor cannot map it to the normalizer of its rows; rename the layout in ACF to a name that is not a decimal integer";
                    $valid = false;
                    continue;
                }

                if (str_contains($layout->name, self::DOC_COMMENT_END)) {
                    $errors[] = "E002: ACF field '{$path}' in group '{$groupKey}' has a layout named '{$layout->name}', which contains '*/' and cannot be written in the PHPDoc type of the generated accessor; rename the layout in ACF";
                    $valid = false;
                    continue;
                }

                if (\array_key_exists($layout->name, $layoutNames)) {
                    $errors[] = "E002: ACF field '{$path}' in group '{$groupKey}' has more than one layout named '{$layout->name}'; rename one of them";
                    $valid = false;
                    continue;
                }

                $layoutNames[$layout->name] = true;
                $valid = $this->checkSubFields($layout->subFields, $path, $groupKey, $layout->name, $errors, $warnings) && $valid;
            }
        }

        return $valid;
    }

    /**
     * @param list<FieldDefinition> $subFields
     * @param list<string> $errors
     * @param list<string> $warnings
     */
    private function checkSubFields(array $subFields, string $path, string $groupKey, ?string $layout, array &$errors, array &$warnings): bool
    {
        $valid = true;
        /** @var array<string, true> $names */
        $names = $layout === null ? [] : ['acf_fc_layout' => true];
        $where = $layout === null ? "ACF field '{$path}'" : "layout '{$layout}' of ACF field '{$path}'";

        foreach ($this->types->valueFields($subFields) as $subField) {
            // PHPは10進の整数の文字列の配列のキーを整数にするため、ACFが返すgroup・行の配列はその名前を文字列のキーで持てない
            if (\is_int(array_key_first([$subField->name => true]))) {
                $errors[] = "E002: {$where} in group '{$groupKey}' has a sub field named '{$subField->name}', which PHP converts to the integer array key {$subField->name}, so the generated accessor cannot return it as a field name; rename the sub field in ACF to a name that is not a decimal integer";
                $valid = false;
                continue;
            }

            if (str_contains($subField->name, self::DOC_COMMENT_END)) {
                $errors[] = "E002: {$where} in group '{$groupKey}' has a sub field named '{$subField->name}', which contains '*/' and cannot be written in the PHPDoc type of the generated accessor; rename the sub field in ACF";
                $valid = false;
                continue;
            }

            if (\array_key_exists($subField->name, $names)) {
                $errors[] = $subField->name === 'acf_fc_layout' && $layout !== null
                    ? "E002: {$where} in group '{$groupKey}' has a sub field named 'acf_fc_layout', which ACF uses for the layout name of each row; rename the sub field"
                    : "E002: {$where} in group '{$groupKey}' has more than one sub field named '{$subField->name}'; rename one of them";
                $valid = false;
                continue;
            }

            $names[$subField->name] = true;
            $valid = $this->checkValueField($subField, "{$path}.{$subField->name}", $groupKey, $errors, $warnings) && $valid;
        }

        return $valid;
    }

    /**
     * @param array<string, string> $methods 生成済み・予約済みのメソッド名(小文字 => 説明)
     * @param array<string, string> $constants 生成済みの定数名 => 説明
     * @param list<string> $errors
     * @param list<string> $warnings
     */
    private function accessorFor(
        FieldGroup $group,
        FieldDefinition $field,
        BridgeConfig $config,
        ClassImports $imports,
        array &$methods,
        array &$constants,
        array &$errors,
        array &$warnings,
    ): ?AccessorDefinition {
        $methodMapKey = $group->key . '.' . $field->name;
        $methodName = $config->methodNameMap[$methodMapKey] ?? null;
        $resolution = "set BridgeConfig::\$methodNameMap['{$methodMapKey}'] to another method name (the constants are named after it)";
        $owner = "ACF field '{$field->name}' in group '{$group->key}'";

        if ($methodName === null) {
            if (!NameConverter::isAccessorEligible($field->name)) {
                $warnings[] = "W009: ACF field '{$field->name}' in group '{$group->key}' is not ASCII snake_case; accessor was skipped; set BridgeConfig::\$methodNameMap['{$methodMapKey}'] to an ASCII method name to generate it";

                return null;
            }

            $methodName = NameConverter::methodName($field->name);
            $constName = NameConverter::constName($field->name);
        } elseif (!$this->isMethodName($methodName)) {
            $errors[] = "E002: methodNameMap '{$methodMapKey}' resolves to invalid method '{$methodName}'";

            return null;
        } else {
            $constName = $this->constNameFromMethod($methodName);
        }

        if ($constName === null || strtoupper($constName) === 'CLASS') {
            $errors[] = "E002: {$owner} cannot be generated because 'CLASS' is not allowed as a PHP class constant name; {$resolution}";

            return null;
        }

        $studly = ucfirst($methodName);
        $dateTimeMethodName = $this->types->hasDateTimeAccessor($field) ? $methodName . 'AsDateTime' : null;
        $declaredMethods = array_filter([$methodName, 'set' . $studly, $dateTimeMethodName, 'has' . $studly, 'delete' . $studly], static fn(?string $name): bool => $name !== null);
        $declaredConstants = [$constName, 'KEY_' . $constName];
        $collisions = [];

        foreach ($declaredMethods as $method) {
            $registered = $methods[strtolower($method)] ?? null;

            if ($registered !== null) {
                $collisions[] = "method '{$method}' collides with {$registered}";
            }
        }

        if ($collisions !== []) {
            $collisions[\count($collisions) - 1] .= ' (PHP method names are case-insensitive)';
        }

        foreach ($declaredConstants as $constant) {
            $registered = $constants[$constant] ?? null;

            if ($registered !== null) {
                $collisions[] = "constant '{$constant}' collides with {$registered}";
            }
        }

        if ($collisions !== []) {
            $errors[] = "E002: the accessor for {$owner} cannot be generated: " . implode('; ', $collisions) . "; {$resolution}";

            return null;
        }

        foreach ($declaredMethods as $method) {
            $methods[strtolower($method)] = "the method '{$method}' generated for {$owner}";
        }

        foreach ($declaredConstants as $constant) {
            $constants[$constant] = "the constant '{$constant}' generated for {$owner}";
        }

        return new AccessorDefinition(
            groupKey: $group->key,
            groupTitle: $group->title,
            sourceFile: $group->sourceFile,
            field: $field,
            constName: $constName,
            keyConstName: 'KEY_' . $constName,
            methodName: $methodName,
            setterName: 'set' . $studly,
            hasName: 'has' . $studly,
            deleteName: 'delete' . $studly,
            dateTimeMethodName: $dateTimeMethodName,
            mapping: $this->types->map($field, $imports, $imports),
        );
    }

    /**
     * @param list<AccessorDefinition> $accessors
     * @param ClassImports $imports accessorsFor()がアクセサの型を決めたときと同じ、生成クラスのClassImports
     */
    private function renderClass(TargetBucket $bucket, array $accessors, GeneratorContext $context, ClassImports $imports): string
    {
        $target = $bucket->target;
        $optionsPostId = $target->kind === TargetKind::Options ? $this->optionsPostId($target->subtype, $context) : null;
        $traitName = $imports->ref('AcfFieldAccess');
        $body = [];

        foreach ($accessors as $accessor) {
            $body[] = '';
            $body[] = '    /** ' . $this->fieldDescription($accessor) . ' */';
            $body[] = "    public const {$accessor->constName} = " . $this->phpString($accessor->field->name) . ';';
            $body[] = "    public const {$accessor->keyConstName} = " . $this->phpString($accessor->field->key) . ';';
        }

        $body = [...$body, ...$this->factoryLines($target, $optionsPostId, $imports)];

        foreach ($accessors as $accessor) {
            $body = [...$body, ...$this->getterLines($accessor, $imports), ...$this->setterLines($accessor, $imports)];

            if ($accessor->dateTimeMethodName !== null) {
                $body = [...$body, ...$this->dateTimeGetterLines($accessor, $imports)];
            }

            $body = [...$body, ...$this->hasAndDeleteLines($accessor)];
        }

        $lines = $this->headerLines(
            "{$target->className} — ACF typed accessors for {$this->targetDescription($target)}.",
            $context->config->namespace,
            $this->sourceLines($bucket->groups()),
        );
        $lines = [...$lines, ...$imports->useLines(), ''];
        $localAliases = $imports->localAliasLines();
        $typeImports = $imports->typeImportLines();
        // php-cs-fixerのphpdoc_separationと同じく、`@phpstan-type`と`@phpstan-import-type`の間を空行で分ける
        $typeLines = $localAliases !== [] && $typeImports !== [] ? [...$localAliases, ' *', ...$typeImports] : [...$localAliases, ...$typeImports];

        if ($typeLines !== []) {
            $lines = [...$lines, '/**', ...$typeLines, ' */'];
        }

        $lines = [...$lines, "final class {$target->className}", '{', "    use {$traitName};", ...$body, '}'];

        return implode("\n", $lines) . "\n";
    }

    /**
     * @param list<FieldGroup> $groups
     *
     * @return list<string>
     */
    private function sourceLines(array $groups): array
    {
        /** @var array<string, string> $sources */
        $sources = [];

        foreach ($groups as $group) {
            // ディレクトリだけが違う同じ名前のファイル(子テーマと親テーマのacf-json等)を1つにまとめないよう、パスで集める
            $sources[$group->sourceFile] = basename($group->sourceFile) . ' (' . $group->title . ')';
        }

        $lines = array_values($sources);
        sort($lines, SORT_STRING);

        return $lines;
    }

    /**
     * @param list<string> $sourceLines
     *
     * @return list<string>
     */
    private function headerLines(string $title, string $namespace, array $sourceLines, string $extra = ''): array
    {
        $lines = [
            '<?php',
            '',
            '/**',
            ' * ' . $this->docText($title),
            ' *',
            ' * ' . self::GENERATED_MARKER,
        ];

        if ($extra !== '') {
            $lines[] = ' * ' . $extra;
        }

        $lines[] = ' *';
        $lines[] = ' * このファイルは自動生成。手で編集しないこと(次回syncで上書きされる)。';
        $lines[] = ' * 再生成: composer acf:sync (vendor/bin/tms-acf sync)';
        $lines[] = ' *';
        $lines[] = ' * sources:';

        if ($sourceLines === []) {
            $lines[] = ' *   (none)';
        } else {
            foreach ($sourceLines as $sourceLine) {
                $lines[] = ' *   ' . $this->docText($sourceLine);
            }
        }

        $lines[] = ' */';
        $lines[] = '';
        $lines[] = 'declare(strict_types=1);';
        $lines[] = '';
        $lines[] = "namespace {$namespace};";
        $lines[] = '';

        return $lines;
    }

    /**
     * ファクトリ。of()はObjectType::resolveId()でIDを検査する(1未満はInvalidArgumentException。ACFはpost_idの0を
     * 現在のループの投稿に置き換え、WordPressのメタの関数は負のIDをabsint()で別のIDにするため)。
     *
     * @return list<string>
     */
    private function factoryLines(GenerationTarget $target, ?string $optionsPostId, ClassImports $imports): array
    {
        if ($target->kind === TargetKind::Options) {
            return [
                '',
                '    public static function instance(): self',
                '    {',
                '        return new self(' . $this->phpString($optionsPostId ?? 'option') . ');',
                '    }',
            ];
        }

        [$parameter, $class, $case, $prefix] = match ($target->kind) {
            TargetKind::Post => ['post', 'WP_Post', 'Post', ''],
            TargetKind::Term => ['term', 'WP_Term', 'Term', "'term_' . "],
            TargetKind::User => ['user', 'WP_User', 'User', "'user_' . "],
        };

        return [
            '',
            "    public static function of({$imports->ref($class)}|int \${$parameter}): self",
            '    {',
            "        return new self({$prefix}{$imports->ref('ObjectType')}::{$case}->resolveId(\${$parameter}));",
            '    }',
        ];
    }

    /**
     * @return list<string>
     */
    private function getterLines(AccessorDefinition $accessor, ClassImports $imports): array
    {
        $mapping = $accessor->mapping;
        $lines = [''];

        if ($this->docTypeDiffers($mapping->getterNativeType, $mapping->getterDocType)) {
            $lines = [
                ...$lines,
                '    /**',
                '     * ' . $this->fieldDescription($accessor),
                '     *',
                "     * @return {$mapping->getterDocType}",
                '     */',
            ];
        } else {
            $lines[] = '    /** ' . $this->fieldDescription($accessor) . ' */';
        }

        $lines[] = "    public function {$accessor->methodName}(): {$mapping->getterNativeType}";
        $lines[] = '    {';

        if (!$this->hasSavedName($accessor->field)) {
            $call = $this->helperCall($accessor->field, $mapping, "\$this->{$mapping->coercionHelper}(", ["self::{$accessor->keyConstName}"], '        ', $imports);
        } elseif ($mapping->coercionHelper === 'acfMixed') {
            $call = ["\$this->acfClonedValue(self::{$accessor->keyConstName}, self::{$accessor->constName})"];
        } else {
            // 保存名のフィールドは、保存名で読んだ値を*Of()のヘルパで検査する(位置は保存名)
            $call = $this->helperCall($accessor->field, $mapping, "\$this->{$mapping->coercionHelper}Of(", ["\$this->acfClonedValue(self::{$accessor->keyConstName}, self::{$accessor->constName})", "self::{$accessor->constName}"], '        ', $imports);
        }

        $lines = [...$lines, ...$this->wrapped('        return ', $call, ';')];
        $lines[] = '    }';

        return $lines;
    }

    /**
     * ヘルパの呼び出しの式。1行目は呼び出し側が字下げと前置を付ける断片で、2行目以降は$indentを基準に字下げした行。
     * group・repeater・flexible_contentは、サブフィールドごとに値を受け取るヘルパ(`*Of()`)を呼ぶ関数を引数に渡す。
     *
     * @param list<string> $arguments
     *
     * @return list<string>
     */
    private function helperCall(FieldDefinition $field, TypeMapping $mapping, string $head, array $arguments, string $indent, ClassImports $imports): array
    {
        if ($mapping->objectClass !== null) {
            $arguments[] = "{$mapping->objectClass}::class";
        }

        $call = $head . implode(', ', $arguments);

        $argument = match ($mapping->coercionHelper) {
            'acfGroup' => $this->shapeClosure('group', $field->subFields, null, $indent, $imports),
            'acfRows' => $this->shapeClosure('row', $field->subFields, null, $indent, $imports),
            'acfLayouts' => $this->layoutsArgument($field, $indent, $imports),
            default => null,
        };

        if ($argument === null) {
            return [$call . ')'];
        }

        return $this->wrapped($call . ', ', $argument, ')');
    }

    /**
     * サブフィールドの値の式。値は`${$var}['名前'] ?? null`、位置は`$path . '.名前'`。未知の型(acfMixed)は値をそのまま使う。
     *
     * @return list<string>
     */
    private function subFieldExpression(FieldDefinition $field, string $var, string $indent, ClassImports $imports): array
    {
        // サブフィールドのsetterは生成しないため、setter側の型の参照は生成クラスのuseに記録しない
        $mapping = $this->types->map($field, $imports, ClassImports::discarding());
        $value = "\${$var}[" . $this->phpString($field->name) . '] ?? null';

        if ($mapping->coercionHelper === 'acfMixed') {
            return [$value];
        }

        return $this->helperCall($field, $mapping, "\$this->{$mapping->coercionHelper}Of(", [$value, '$path . ' . $this->phpString('.' . $field->name)], $indent, $imports);
    }

    /**
     * サブフィールドの配列(group・repeaterの行・flexible_contentのレイアウトの行)を正規化する関数。
     *
     * @param list<FieldDefinition> $subFields
     *
     * @return list<string>
     */
    private function shapeClosure(string $var, array $subFields, ?string $layout, string $indent, ClassImports $imports): array
    {
        $entryIndent = $indent . '    ';
        $entries = $layout === null ? [] : ["{$entryIndent}'acf_fc_layout' => " . $this->phpString($layout) . ','];

        foreach ($this->types->valueFields($subFields) as $subField) {
            $expression = $this->subFieldExpression($subField, $var, $entryIndent, $imports);
            $entries = [...$entries, ...$this->wrapped($entryIndent . $this->phpString($subField->name) . ' => ', $expression, ',')];
        }

        $head = "fn(array \${$var}, string \$path): array => ";

        if ($entries === []) {
            return [$head . '[]'];
        }

        return [$head . '[', ...$entries, $indent . ']'];
    }

    /**
     * flexible_contentのレイアウトの名前 => 行を正規化する関数、の配列(レイアウトが1つ以上のとき。0件はacfEmptyLayouts)。
     *
     * @return list<string>
     */
    private function layoutsArgument(FieldDefinition $field, string $indent, ClassImports $imports): array
    {
        $entryIndent = $indent . '    ';
        $lines = ['['];

        foreach ($field->layouts as $layout) {
            $closure = $this->shapeClosure('row', $layout->subFields, $layout->name, $entryIndent, $imports);
            $lines = [...$lines, ...$this->wrapped($entryIndent . $this->phpString($layout->name) . ' => ', $closure, ',')];
        }

        $lines[] = $indent . ']';

        return $lines;
    }

    /**
     * 式の行の1行目に$prefixを、最後の行に$suffixを付ける。
     *
     * @param list<string> $expression
     *
     * @return list<string>
     */
    private function wrapped(string $prefix, array $expression, string $suffix): array
    {
        $lines = $expression;
        $lines[0] = $prefix . $lines[0];
        $lines[\count($lines) - 1] .= $suffix;

        return $lines;
    }

    /**
     * @return list<string>
     */
    private function setterLines(AccessorDefinition $accessor, ClassImports $imports): array
    {
        $mapping = $accessor->mapping;
        $lines = [''];

        if ($mapping->setterDocType !== '') {
            $lines[] = '    /** @param ' . $mapping->setterDocType . ' $value */';
        }

        $lines[] = "    public function {$accessor->setterName}({$mapping->setterNativeType} \$value): void";
        $lines[] = '    {';

        $target = $this->targetArguments($accessor);

        if ($mapping->dateRawFormat !== '') {
            $lines[] = "        \$this->{$this->helperName($accessor, 'UpdateDate')}({$target}, \$value, " . $this->phpString($mapping->dateRawFormat) . ');';
        } else {
            $lines[] = "        \$this->{$this->helperName($accessor, 'Update')}({$target}, \$value);";
        }

        $lines[] = '    }';

        return $lines;
    }

    /**
     * @return list<string>
     */
    private function dateTimeGetterLines(AccessorDefinition $accessor, ClassImports $imports): array
    {
        $methodName = $accessor->dateTimeMethodName;

        if ($methodName === null) {
            return [];
        }

        return [
            '',
            "    public function {$methodName}(): ?{$imports->ref('DateTimeImmutable')}",
            '    {',
            "        return \$this->{$this->helperName($accessor, 'DateTime')}({$this->targetArguments($accessor)}, " . $this->phpString($accessor->mapping->dateRawFormat) . ');',
            '    }',
        ];
    }

    /** @return list<string> */
    private function hasAndDeleteLines(AccessorDefinition $accessor): array
    {
        return [
            '',
            "    public function {$accessor->hasName}(): bool",
            '    {',
            "        return \$this->{$this->helperName($accessor, 'Has')}({$this->targetArguments($accessor)});",
            '    }',
            '',
            "    public function {$accessor->deleteName}(): bool",
            '    {',
            "        return \$this->{$this->helperName($accessor, 'Delete')}({$this->targetArguments($accessor)});",
            '    }',
        ];
    }

    /**
     * cloneの`prefix_name`で、保存名(フィールドの名前)がACFに登録された定義の名前と違うフィールドか。
     * そのフィールドは、元のkeyの定義を保存名に差し替えて読み書きするヘルパ(acfCloned*())を使う。
     */
    private function hasSavedName(FieldDefinition $field): bool
    {
        $definitionName = $field->raw[CloneResolver::DEFINITION_NAME] ?? null;

        return \is_string($definitionName) && $definitionName !== $field->name;
    }

    /** traitのヘルパの名前。保存名のフィールドは`acfCloned{$suffix}`、それ以外は`acf{$suffix}`。 */
    private function helperName(AccessorDefinition $accessor, string $suffix): string
    {
        return ($this->hasSavedName($accessor->field) ? 'acfCloned' : 'acf') . $suffix;
    }

    /** ヘルパに渡すフィールドの指定。保存名のフィールドはkeyと保存名、それ以外はkey。 */
    private function targetArguments(AccessorDefinition $accessor): string
    {
        return $this->hasSavedName($accessor->field)
            ? "self::{$accessor->keyConstName}, self::{$accessor->constName}"
            : "self::{$accessor->keyConstName}";
    }

    /**
     * PHPDocの型がPHPの型と違うか(同じならphp-cs-fixerのno_superfluous_phpdoc_tagsが@returnを消すため、書かない)。
     * `?T`は`T|null`とみなし、unionの並びは問わない。
     */
    private function docTypeDiffers(string $nativeType, string $docType): bool
    {
        $canonical = static function (string $type): array {
            $parts = str_starts_with($type, '?') ? [substr($type, 1), 'null'] : explode('|', $type);
            sort($parts, SORT_STRING);

            return $parts;
        };

        return $canonical($nativeType) !== $canonical($docType);
    }

    /**
     * 管理キーの一覧(AcfManifest)を生成する。管理キーは`wp tmswp acf check`のE101と同じManagedKeyCollectorで集める。
     * ヘッダは、全入力の集約ハッシュ(source-hash)と、管理キーを持つグループの由来のJSONを記す。
     *
     * @param list<FieldGroup> $groups cloneを解決したグループ
     */
    private function renderManifest(array $groups, GeneratorContext $context): string
    {
        $managedKeys = (new ManagedKeyCollector($this->locations, $this->types))->collect($groups, $context->config);
        $managedGroupKeys = array_flip(array_map(static fn(ManagedKey $managedKey): string => $managedKey->groupKey, $managedKeys));
        $lines = $this->headerLines(
            'AcfManifest — ACF managed keys.',
            $context->config->namespace,
            $this->sourceLines(array_values(array_filter($groups, static fn(FieldGroup $group): bool => \array_key_exists($group->key, $managedGroupKeys)))),
            'source-hash: sha256:' . $context->sourceHash,
        );
        $usesObjectType = false;

        foreach ($managedKeys as $managedKey) {
            if ($managedKey->objectType !== null) {
                $usesObjectType = true;
                break;
            }
        }

        $lines[] = 'use TMSWP\\AcfBridge\\Manifest\\ManagedKey;';

        if ($usesObjectType) {
            $lines[] = 'use TMSWP\\Core\\Meta\\ObjectType;';
        }

        $lines[] = '';
        $lines[] = 'final class AcfManifest';
        $lines[] = '{';
        $lines[] = '    /** @return list<ManagedKey> */';
        $lines[] = '    public static function managedKeys(): array';
        $lines[] = '    {';
        $lines[] = '        return [';

        foreach ($managedKeys as $managedKey) {
            $lines[] = '            new ManagedKey('
                . ($managedKey->objectType !== null ? 'ObjectType::' . $managedKey->objectType->name : 'null') . ', '
                . $this->phpString($managedKey->objectSubtype) . ', '
                . $this->phpString($managedKey->metaKey) . ', '
                . $this->phpString($managedKey->fieldKey) . ', '
                . $this->phpString($managedKey->groupKey)
                . '),';
        }

        $lines[] = '        ];';
        $lines[] = '    }';
        $lines[] = '}';

        return implode("\n", $lines) . "\n";
    }

    /**
     * オプションページのACFのpost_id。GeneratorContext::$optionsPagePostIds(acf-jsonのui_options_pageと
     * BridgeConfigのoptionsPagePostIds)に無ければ'option'。
     */
    private function optionsPostId(string $menuSlug, GeneratorContext $context): string
    {
        return $context->optionsPagePostIds[$menuSlug] ?? 'option';
    }

    private function targetDescription(GenerationTarget $target): string
    {
        if ($target->template !== null) {
            return 'post template ' . $this->phpString($target->template);
        }

        return match ($target->kind) {
            TargetKind::Post => 'post_type ' . $this->phpString($target->subtype),
            TargetKind::Term => 'taxonomy ' . $this->phpString($target->subtype),
            TargetKind::User => 'users',
            TargetKind::Options => 'options_page ' . $this->phpString($target->subtype),
        };
    }

    private function fieldDescription(AccessorDefinition $accessor): string
    {
        $label = $accessor->field->label !== '' ? $accessor->field->label : $accessor->field->name;

        return $this->docText("{$label} ({$accessor->field->type}, {$accessor->groupKey})");
    }

    /**
     * docコメントに埋め込む説明の文(ラベル・グループのタイトル・対象の名前等。acf-jsonの任意の文字列を含む)。docコメントを
     * 閉じる並び(アスタリスクとスラッシュ)のスラッシュの前にバックスラッシュを入れ、生成物が構文エラーにならないようにする。
     */
    private function docText(string $text): string
    {
        return str_replace(self::DOC_COMMENT_END, '*\/', $text);
    }

    private function targetKey(GenerationTarget $target): string
    {
        return $target->key();
    }

    private function isClassName(string $className): bool
    {
        return preg_match('/^[A-Z][A-Za-z0-9]*$/', $className) === 1;
    }

    private function isMethodName(string $methodName): bool
    {
        return preg_match('/^[a-z][A-Za-z0-9]*$/', $methodName) === 1;
    }

    private function constNameFromMethod(string $methodName): string
    {
        $snake = preg_replace('/(?<!^)[A-Z]/', '_$0', $methodName);

        return strtoupper((string) $snake);
    }

    private function phpString(string $value): string
    {
        return "'" . str_replace(['\\', "'"], ['\\\\', "\\'"], $value) . "'";
    }
}
