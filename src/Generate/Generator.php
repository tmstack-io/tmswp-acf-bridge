    /** docコメントを閉じる並び。生成物のdocコメントに埋め込む文字列は、この並びを含んではならない */
    private const DOC_COMMENT_END = '*' . '/';

    /** 生成クラスが自分で宣言するファクトリの名前(TargetKindにかかわらず予約する) */
    private const array FACTORY_METHODS = ['of', 'instance'];

