<?php

declare(strict_types=1);

namespace TMSWP\AcfBridge\Tests\Unit\Cli;

use Closure;
use PHPUnit\Framework\Attributes\DataProvider;
use TMSWP\AcfBridge\BridgeConfig;
use TMSWP\AcfBridge\Cli\SyncRunner;
use TMSWP\Testing\UnitTestCase;

/**
 * WP-CLI版とtms-acfが共有する生成・照合(SyncRunner)のうち、checkの統一diffとI002。WordPressを使わない。
 */
final class SyncRunnerTest extends UnitTestCase
{
    private const GROUP = <<<'JSON'
{
    "key": "group_common",
    "title": "Common",
    "location": [[{"param": "post_type", "operator": "==", "value": "runner_common"}]],
    "fields": [
        {"key": "field_note", "name": "note", "label": "Note", "type": "text"},
        {"key": "field_title", "name": "title", "label": "Title", "type": "text"}
    ]
}
JSON;

    private const GENERATED_FILE = 'RunnerCommonFields.php';

    /**
     * checkは、modifiedのファイルごとに、今のファイルから生成した内容への統一diff(前後3行の文脈を付けた1つのhunk)を
     * 「modified: {ファイル}」の後に表示し、exit 1で終わる。
     */
    public function testCheckShowsUnifiedDiffOfModifiedFile(): void
    {
        $config = $this->syncedConfig();
        $path = $config->outputDir . '/' . self::GENERATED_FILE;
        $generated = (string) file_get_contents($path);
        $lines = explode("\n", substr($generated, 0, -1));
        $index = (int) array_search('    public function note(): string', $lines, true);
        self::assertGreaterThan(3, $index);
        $edited = $lines;
        $edited[$index] = '    public function memo(): string';
        self::assertNotFalse(file_put_contents($path, implode("\n", $edited) . "\n"));

        $outcome = (new SyncRunner())->check($config, false);

        self::assertSame(1, $outcome['status']);
        self::assertSame([
            'modified: ' . self::GENERATED_FILE,
            '--- a/' . self::GENERATED_FILE,
            '+++ b/' . self::GENERATED_FILE,
            '@@ -' . ($index - 2) . ',7 +' . ($index - 2) . ',7 @@',
            ' ' . $lines[$index - 3],
            ' ' . $lines[$index - 2],
            ' ' . $lines[$index - 1],
            '-    public function memo(): string',
            '+    public function note(): string',
            ' ' . $lines[$index + 1],
            ' ' . $lines[$index + 2],
            ' ' . $lines[$index + 3],
            'Run: composer acf:sync (vendor/bin/tms-acf sync or wp tmswp acf sync)',
        ], $outcome['lines']);
    }

    /** 統一diffは、ファイルごとに先頭の40行だけを表示する。空のファイルは、生成した全行の追加として表す。 */
    public function testUnifiedDiffIsLimitedToFortyLines(): void
    {
        $config = $this->syncedConfig();
        $path = $config->outputDir . '/' . self::GENERATED_FILE;
        $generated = (string) file_get_contents($path);
        $generatedLines = explode("\n", substr($generated, 0, -1));
        self::assertGreaterThan(40, \count($generatedLines));
        self::assertNotFalse(file_put_contents($path, ''));

        $outcome = (new SyncRunner())->check($config, false);

        self::assertSame(1, $outcome['status']);
        self::assertSame([
            'modified: ' . self::GENERATED_FILE,
            '--- a/' . self::GENERATED_FILE,
            '+++ b/' . self::GENERATED_FILE,
            '@@ -0,0 +1,' . \count($generatedLines) . ' @@',
            ...array_map(static fn(string $line): string => '+' . $line, \array_slice($generatedLines, 0, 37)),
            'Run: composer acf:sync (vendor/bin/tms-acf sync or wp tmswp acf sync)',
        ], $outcome['lines']);
    }

    /**
     * outputDirにある、生成物でなく@generatedのマーカーも無いPHPファイルは、syncもcheckもI002として表示し、syncは
     * 削除しない(マーカーのある孤児だけを削除する)。I002はcheck --strictを失敗させない。
     */
    public function testUnmarkedFilesAreReportedAsI002AndKept(): void
    {
        $config = $this->syncedConfig();
        $helper = $config->outputDir . '/Helper.php';
        $orphan = $config->outputDir . '/OrphanFields.php';
        self::assertNotFalse(file_put_contents($helper, "<?php\n\n// hand-written\n"));
        self::assertNotFalse(file_put_contents($orphan, "<?php\n\n// @generated by tmswp/acf-bridge\n"));
        $i002 = "I002: Helper.php in {$config->outputDir} has no @generated marker; it is not a generated file and was not deleted";

        $check = (new SyncRunner())->check($config, true);
        self::assertSame(1, $check['status']);
        self::assertSame([$i002, 'orphan: OrphanFields.php', 'Run: composer acf:sync (vendor/bin/tms-acf sync or wp tmswp acf sync)'], $check['lines']);

        $sync = (new SyncRunner())->sync($config, false);
        self::assertSame(0, $sync['status']);
        self::assertSame([$i002, 'write: AcfManifest.php', 'write: RunnerCommonFields.php', 'delete: OrphanFields.php'], $sync['lines']);
        self::assertFileExists($helper);
        self::assertFileDoesNotExist($orphan);

        $strict = (new SyncRunner())->check($config, true);
        self::assertSame(0, $strict['status']);
        self::assertSame([$i002], $strict['lines']);
    }

    /**
     * 最終行の改行の有無の差も、削除行・追加行と標準の注記`\ No newline at end of file`で示す。checkとdry-runは同じdiffを
     * 出し、そのdiffは`git apply`で今のファイルを生成した内容に直せる。
     *
     * @param Closure(string): string $edit 生成した内容から、今のファイルの内容を作る
     */
    #[DataProvider('trailingNewlineEdits')]
    public function testUnifiedDiffKeepsTheTrailingNewline(Closure $edit, string $expectedTail): void
    {
        $config = $this->syncedConfig();
        $path = $config->outputDir . '/' . self::GENERATED_FILE;
        $generated = (string) file_get_contents($path);
        self::assertNotFalse(file_put_contents($path, $edit($generated)));

        $check = (new SyncRunner())->check($config, false);
        $dryRun = (new SyncRunner())->sync($config, true);

        self::assertSame(1, $check['status']);
        $diff = \array_slice($check['lines'], 1, -1);
        self::assertSame(['modified: ' . self::GENERATED_FILE, ...$diff], \array_slice($dryRun['lines'], 0, \count($diff) + 1));
        self::assertSame($expectedTail, implode("\n", \array_slice($diff, -substr_count($expectedTail, "\n") - 1)));

        $patch = $config->outputDir . '/../change.patch';
        self::assertNotFalse(file_put_contents($patch, implode("\n", $diff) . "\n"));
        self::assertSame([0, ''], $this->git(['apply', '--check', $patch], $config->outputDir));
        self::assertSame([0, ''], $this->git(['apply', $patch], $config->outputDir));
        self::assertSame($generated, file_get_contents($path));
    }

    /** @return iterable<string, array{Closure(string): string, string}> */
    public static function trailingNewlineEdits(): iterable
    {
        yield 'the last newline removed' => [
            static fn(string $generated): string => substr($generated, 0, -1),
            "-}\n\\ No newline at end of file\n+}",
        ];
        yield 'the last line changed without a newline' => [
            static fn(string $generated): string => substr($generated, 0, -2) . '} // edited',
            "-} // edited\n\\ No newline at end of file\n+}",
        ];
        yield 'a line added after the last newline' => [
            static fn(string $generated): string => $generated . '// appended',
            " }\n-// appended\n\\ No newline at end of file",
        ];
    }

    /**
     * outputDirのPHPファイルを読めない場合は、マーカーの有無を決められないため、I002にも成功にもしない。checkはexit 2、
     * syncはexit 1で終わり、syncはファイルを消さない。
     */
    public function testUnreadableFileInOutputDirFailsTheCommand(): void
    {
        $config = $this->syncedConfig();
        $orphan = $config->outputDir . '/OrphanFields.php';
        self::assertNotFalse(file_put_contents($orphan, "<?php\n\n// @generated by tmswp/acf-bridge\n"));
        self::assertTrue(chmod($orphan, 0000));
        $error = "E102: failed to read {$orphan} in outputDir to check the @generated marker; fix the file permissions or remove the file";

        try {
            self::assertFalse(is_readable($orphan), 'the test needs a user who cannot read a file with mode 0000');

            self::assertSame(['lines' => [$error], 'status' => 2, 'message' => ''], (new SyncRunner())->check($config, true));
            self::assertSame(['lines' => [$error], 'status' => 1, 'message' => ''], (new SyncRunner())->sync($config, false));
            self::assertSame(['lines' => [$error], 'status' => 1, 'message' => ''], (new SyncRunner())->sync($config, true));
            self::assertFileExists($orphan);
        } finally {
            chmod($orphan, 0644);
        }

        self::assertSame("<?php\n\n// @generated by tmswp/acf-bridge\n", file_get_contents($orphan));
    }

    /**
     * dry-runは、modified・missing・マーカー付きの孤児の差分を返すが、outputDirのファイル(有無と内容)を変えない。
     */
    public function testDryRunReportsDifferencesWithoutWriting(): void
    {
        $config = $this->syncedConfig();
        $path = $config->outputDir . '/' . self::GENERATED_FILE;
        self::assertNotFalse(file_put_contents($path, str_replace('public function note(): string', 'public function memo(): string', (string) file_get_contents($path))));
        self::assertTrue(unlink($config->outputDir . '/AcfManifest.php'));
        self::assertNotFalse(file_put_contents($config->outputDir . '/OrphanFields.php', "<?php\n\n// @generated by tmswp/acf-bridge\n"));
        $before = $this->snapshot($config->outputDir);

        $outcome = (new SyncRunner())->sync($config, true);

        self::assertSame(0, $outcome['status']);
        self::assertSame('ACF bridge sync dry-run completed', $outcome['message']);
        self::assertContains('missing: AcfManifest.php', $outcome['lines']);
        self::assertContains('modified: ' . self::GENERATED_FILE, $outcome['lines']);
        self::assertContains('+    public function note(): string', $outcome['lines']);
        self::assertContains('orphan: OrphanFields.php', $outcome['lines']);
        self::assertSame($before, $this->snapshot($config->outputDir));
    }

    /**
     * ディレクトリの中のファイル名 => 内容。
     *
     * @return array<string, string>
     */
    private function snapshot(string $dir): array
    {
        $files = [];

        $names = scandir($dir);
        self::assertIsArray($names);

        foreach ($names as $name) {
            if (is_file($dir . '/' . $name)) {
                $files[$name] = (string) file_get_contents($dir . '/' . $name);
            }
        }

        return $files;
    }

    /**
     * @param list<string> $arguments
     *
     * @return array{int, string} 終了コードと標準エラー出力
     */
    private function git(array $arguments, string $cwd): array
    {
        $process = proc_open(['git', ...$arguments], [1 => ['pipe', 'w'], 2 => ['pipe', 'w']], $pipes, $cwd);
        self::assertIsResource($process);
        stream_get_contents($pipes[1]);
        $errors = (string) stream_get_contents($pipes[2]);
        fclose($pipes[1]);
        fclose($pipes[2]);

        return [proc_close($process), $errors];
    }

    /** 一時ディレクトリのacf-jsonから生成し、outputDirへ書き込んだ構成。 */
    private function syncedConfig(): BridgeConfig
    {
        $root = (string) realpath($this->createTempDirectory('sync-runner'));
        self::assertTrue(mkdir($root . '/acf-json'));
        self::assertNotFalse(file_put_contents($root . '/acf-json/group_common.json', self::GROUP));
        $config = new BridgeConfig([$root . '/acf-json'], $root . '/app/Acf', 'Example\Runner\Acf');

        $outcome = (new SyncRunner())->sync($config, false);
        self::assertSame(0, $outcome['status'], implode("\n", $outcome['lines']));

        return $config;
    }
}
