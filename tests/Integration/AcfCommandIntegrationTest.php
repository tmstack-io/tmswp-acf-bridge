    /**
     * docs/09 §14「`tms-acf sync`・`wp tmswp acf sync`が決定的出力を生成する(同一入力で2回実行してバイト同一・
     * git statusクリーン)」。fixtureのテーマ・プラグインのacf-jsonとapp/Acfの写しを、同じ名前空間の一時のKernelで、
     * 生成物を消してから`wp tmswp acf sync`を2回実行する。2回の生成物はバイト同一で、コミット済みのfixtureのapp/Acfと
     * 一致する(fixtureでgit statusがクリーンになる)。`tms-acf sync`も同じ写しから同じ生成物を作る。生成はacf-jsonと
     * BridgeConfigだけで決まるため、テーマのfixtureもプラグインの形態のKernelで生成する。
     *
     * @dataProvider fixtureProvider
     */
    public function testWpSyncIsDeterministicAndMatchesTmsAcfSyncAndCommittedFixture(string $fixture, string $namespace): void
    {
        $committed = self::files(self::repositoryRoot() . "/{$fixture}/app/Acf");
        self::assertArrayHasKey('AcfManifest.php', $committed);
        $wpRoot = $this->createFixtureCopy($fixture, $namespace);
        $tmsAcfRoot = $this->createFixtureCopy($fixture, $namespace);

        $first = self::wp($wpRoot, ['tmswp', 'acf', 'sync'], namespace: $namespace);
        $firstFiles = self::files($wpRoot . '/app/Acf');
        $second = self::wp($wpRoot, ['tmswp', 'acf', 'sync'], namespace: $namespace);

        self::assertSame(0, $first['code'], $first['stdout'] . $first['stderr']);
        self::assertSame(0, $second['code'], $second['stdout'] . $second['stderr']);
        self::assertContains('write: AcfManifest.php', self::lines($first['stdout']));
        self::assertContains('Success: ACF bridge sync completed', self::lines($second['stdout']));
        self::assertSame($committed, $firstFiles);
        self::assertSame($firstFiles, self::files($wpRoot . '/app/Acf'));

        foreach ([1, 2] as $run) {
            $tmsAcf = self::tmsAcf($tmsAcfRoot, ['sync']);

            self::assertSame(0, $tmsAcf['code'], "run {$run}: " . $tmsAcf['stdout'] . $tmsAcf['stderr']);
            self::assertSame($firstFiles, self::files($tmsAcfRoot . '/app/Acf'), "run {$run}");
        }
    }

