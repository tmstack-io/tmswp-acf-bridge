    /**
     * docs/09 §14「`wp tmswp acf sync`が`AcfManifest.php`を生成し、`managedKeys()`がacf-json由来のACF管理下キー一覧を
     * 返す。`AcfManifest`クラスが無いとき、…WP-CLIのときだけ`WP_CLI::warning()`で警告して申告しない」。AcfManifestの
     * 無いKernelでも、WP-CLIのプロセスは警告だけで完了し(init 6の申告は行わない)、`wp tmswp acf sync`を実行できる。
     * 生成したAcfManifestを次のプロセスが読み、管理キーを申告する。
     */
    public function testWpSyncGeneratesTheManifestThatTheNextProcessMarks(): void
    {
        $root = $this->createKernel(['acf-json/group_tmswp_cli_post.json' => self::group('group_tmswp_cli_post', 'post', ['tmswp_cli_note'])]);
        $warning = 'Warning: ACF manifest class ' . self::APP_NAMESPACE . '\Acf\AcfManifest is not found; run wp tmswp acf sync --app=' . self::APP_NAMESPACE . ' and deploy the generated files';

        $before = self::wp($root, ['eval', self::PROBE]);

        self::assertSame(0, $before['code'], $before['stdout'] . $before['stderr']);
        self::assertContains($warning, self::lines($before['stderr']));
        self::assertSame(['acf' => true, 'init' => 1, 'marked' => false, 'managedKeys' => null], self::json($before['stdout']));

        $sync = self::wp($root, ['tmswp', 'acf', 'sync']);

        self::assertSame(0, $sync['code'], $sync['stdout'] . $sync['stderr']);
        self::assertContains($warning, self::lines($sync['stderr']));
        self::assertSame(['write: AcfManifest.php', 'write: PostFields.php', 'Success: ACF bridge sync completed'], self::lines($sync['stdout']));
        self::assertFileExists($root . '/app/Acf/AcfManifest.php');

        $after = self::wp($root, ['eval', self::PROBE]);

        self::assertSame(0, $after['code'], $after['stdout'] . $after['stderr']);
        self::assertStringNotContainsString('Warning:', $after['stderr']);
        self::assertSame([
            'acf' => true,
            'init' => 1,
            'marked' => true,
            'managedKeys' => [['post', 'post', 'tmswp_cli_note', 'field_tmswp_cli_post_tmswp_cli_note', 'group_tmswp_cli_post']],
        ], self::json($after['stdout']));
    }

    /**
     * docs/09 §14「`KernelConfig`の`extensions`に渡した`AcfBridge`の登録(Kernelのboot)がACF不在環境でも例外なく完了し、
     * ACF不在でも管理キーの申告(§7.2)が行われる」。ACFを有効なプラグインから外したWP-CLIのプロセスで、AcfBridgeを
     * 登録したKernelがbootし、init(priority 6)で生成物AcfManifestの管理キーを申告する。AcfManifestはWordPressを
     * 起動しない`tms-acf sync`で作る。
     */
    public function testKernelWithAcfBridgeBootsAndMarksManagedKeysWithoutAcf(): void
    {
        $root = $this->createKernel(['acf-json/group_tmswp_cli_post.json' => self::group('group_tmswp_cli_post', 'post', ['tmswp_cli_note'])]);
        $sync = self::tmsAcf($root, ['sync']);
        self::assertSame(0, $sync['code'], $sync['stdout'] . $sync['stderr']);

        $probe = self::wp($root, ['eval', self::PROBE], []);

        self::assertSame(0, $probe['code'], $probe['stdout'] . $probe['stderr']);
        self::assertDoesNotMatchRegularExpression('/Warning|Error|Exception/', $probe['stderr']);
        self::assertSame([
            'acf' => false,
            'init' => 1,
            'marked' => true,
            'managedKeys' => [['post', 'post', 'tmswp_cli_note', 'field_tmswp_cli_post_tmswp_cli_note', 'group_tmswp_cli_post']],
        ], self::json($probe['stdout']));
    }

    /**
     * docs/09 §14「別のストレージ(`AcfMetaStorage`でない)のエンティティの`#[MetaSchema]`とACF管理下キーの重複が、
     * …`wp tmswp acf check`のE101(exit 2)…で検出される」。#[UseMetaStorage]の無い(既定のWpMetaStorageの)投稿タイプが
     * #[MetaSchema]で宣言したキーを、acf-jsonのフィールドグループも持つ。`--strict`の有無によらず、実行時の例外と
     * 同じ説明のE101を出してexit 2になる(生成物を作る前の状態。AcfManifestが無いため実行時の申告は警告だけになる)。
     */
    public function testWpCheckReportsMetaSchemaConflictAsE101(): void
    {
        [$root, $e101] = $this->createConflictingKernel();

        foreach ([[], ['--strict']] as $options) {
            $check = self::wp($root, ['tmswp', 'acf', 'check', ...$options]);

            self::assertSame(2, $check['code'], $check['stdout'] . $check['stderr']);
            self::assertSame([$e101, 'ACF bridge generation failed'], self::lines($check['stdout']));
        }
    }

    /**
     * docs/09 §14「…重複が、実行時例外および`wp tmswp acf check`のE101(exit 2)の両方で検出される」を、生成物の
     * AcfManifestがすでにそのキーを持つ状態(生成物をコミットした後に#[MetaSchema]を足した、よくある順序)で確かめる。
     * `wp tmswp acf check`のプロセスは、起動時(init 6)の申告で止まらずに、E101・exit 2で報告する。`wp tmswp acf sync`は
     * E101で書き込まずにexit 1で終わる。ほかのWP-CLIのコマンド(`wp eval`)は、WP-CLIでないリクエストと同じく、起動時の
     * DuplicateMetaKeyExceptionで止まる(docs/09 §7.3)。
     */
    public function testWpCheckReportsE101AndOtherCommandsStopWhenTheManifestAlreadyHasTheKey(): void
    {
        [$root, $e101] = $this->createConflictingKernel();
        // tms-acfはE101を検査しないため、重複したキーを持つAcfManifestを書く
        $sync = self::tmsAcf($root, ['sync']);
        self::assertSame(0, $sync['code'], $sync['stdout'] . $sync['stderr']);
        $generated = self::files($root . '/app/Acf');
        self::assertStringContainsString("'tmswp_cli_price'", $generated['AcfManifest.php'] ?? '');

        foreach ([[], ['--strict']] as $options) {
            $check = self::wp($root, ['tmswp', 'acf', 'check', ...$options]);

            self::assertSame(2, $check['code'], $check['stdout'] . $check['stderr']);
            self::assertSame([$e101, 'ACF bridge generation failed'], self::lines($check['stdout']));
            self::assertStringNotContainsString('DuplicateMetaKeyException', $check['stderr']);
        }

        $wpSync = self::wp($root, ['tmswp', 'acf', 'sync']);
        self::assertSame(1, $wpSync['code'], $wpSync['stdout'] . $wpSync['stderr']);
        self::assertContains($e101, self::lines($wpSync['stdout']));
        self::assertSame($generated, self::files($root . '/app/Acf'));

        $eval = self::wp($root, ['eval', 'echo "booted";']);
        self::assertNotSame(0, $eval['code'], $eval['stdout'] . $eval['stderr']);
        self::assertStringNotContainsString('booted', $eval['stdout']);
        self::assertStringContainsString("Uncaught TMSWP\\Core\\Exception\\DuplicateMetaKeyException: externally managed meta key 'tmswp_cli_price' for post:tmswp_cli_item", $eval['stderr']);
    }

    /**
     * #[UseMetaStorage]の無い投稿タイプが#[MetaSchema]で宣言したキー(tmswp_cli_price)を、acf-jsonのグループも持つ一時の
     * Kernelを作る。
     *
     * @return array{string, string} Kernelのルートと、`wp tmswp acf check`が出すE101の行
     */
    private function createConflictingKernel(): array
    {
        $entity = <<<'PHP'
            <?php

            declare(strict_types=1);

            namespace TmswpAcfCliProbe\Post;

            use TMSWP\Core\Attribute\AsPostType;
            use TMSWP\Core\Attribute\MetaSchema;
            use TMSWP\Core\Meta\MetaValueType;
            use TMSWP\Core\Post\PostType;
            use TMSWP\Core\Post\PostTypeDefinition;

            #[AsPostType]
            final class CliItemPost extends PostType
            {
                #[MetaSchema(type: MetaValueType::String)]
                public const PRICE = 'tmswp_cli_price';

                public static function definition(): PostTypeDefinition
                {
                    return PostTypeDefinition::create('tmswp_cli_item')->label('CLI item', 'CLI items');
                }
            }
            PHP;
        $root = $this->createKernel([
            'acf-json/group_tmswp_cli_item.json' => self::group('group_tmswp_cli_item', 'tmswp_cli_item', ['tmswp_cli_price']),
            'app/Post/CliItemPost.php' => $entity . "\n",
        ]);
        $class = self::APP_NAMESPACE . '\Post\CliItemPost';
        $e101 = "E101: externally managed meta key 'tmswp_cli_price' for post:tmswp_cli_item is already declared by {$class}::PRICE"
            . " with meta storage TMSWP\\Core\\Meta\\WpMetaStorage; ACF field group 'group_tmswp_cli_item' manages it with meta storage TMSWP\\AcfBridge\\AcfMetaStorage."
            . " Add #[UseMetaStorage(\\TMSWP\\AcfBridge\\AcfMetaStorage::class)] to {$class}, remove the #[MetaSchema] constant PRICE, or remove the key from ACF field group 'group_tmswp_cli_item'";

        return [$root, $e101];
    }

    /**
     * docs/09 §14「`tms-acf check`・`wp tmswp acf check`が、差分なし=0 …を返し、`--strict`で警告も1になる。…同じ構成で
     * 2つのコマンドの出力と終了コードが同じ(tms-acfのE101の注記を除く)」。生成物が最新で警告(W011)だけがある状態で、
     * `--strict`が無ければ0、あれば1になり、どちらも2つのコマンドの出力が同じ。
     */
    public function testChecksAgreeOnInSyncAndStrictWarnings(): void
    {
        $root = $this->createSyncedKernel();
        $warning = "W011: inactive ACF field group 'group_tmswp_cli_inactive' was skipped";

        $lines = self::assertChecksAgree($root, [], 0);

        self::assertSame($warning, $lines[0]);
        self::assertMatchesRegularExpression('/^Success: ACF bridge is in sync\. \(2 files, source-hash sha256:[0-9a-f]{64}\)$/', $lines[1]);
        self::assertCount(2, $lines);
        self::assertSame([$warning, 'ACF bridge strict check failed with warnings'], self::assertChecksAgree($root, ['--strict'], 1));
    }

    /**
     * docs/09 §14「…差分あり=1 …。modifiedのファイルは統一diffの先頭40行を表示する。同じ構成で2つのコマンドの出力と
     * 終了コードが同じ(tms-acfのE101の注記を除く)」。生成物の書き換え(modified)・削除(missing)・@generatedの付いた
     * 余分なファイル(orphan)を、`--strict`の有無によらずexit 1で示し、modifiedには統一diffの先頭40行を付ける。
     */
    public function testChecksAgreeOnDriftWithUnifiedDiffLimitedToFortyLines(): void
    {
        $root = $this->createSyncedKernel();
        $generated = explode("\n", (string) file_get_contents($root . '/app/Acf/PostFields.php'), 2);
        $drift = '';

        for ($i = 1; $i <= 60; ++$i) {
            $drift .= "// drift {$i}\n";
        }

        // 1行目(<?php)の後に60行を足す。debugのKernelの探索がクラスを読むため、クラスの宣言は残す
        self::putFile($root . '/app/Acf/PostFields.php', $generated[0] . "\n" . $drift . ($generated[1] ?? ''));
        self::assertTrue(unlink($root . '/app/Acf/AcfManifest.php'));
        self::putFile($root . '/app/Acf/StaleFields.php', "<?php\n\n/** " . self::GENERATED_MARKER . " */\n\ndeclare(strict_types=1);\n\nnamespace " . self::APP_NAMESPACE . "\\Acf;\n\nfinal class StaleFields {}\n");

        foreach ([[], ['--strict']] as $options) {
            $lines = self::assertChecksAgree($root, $options, 1);
            $modified = array_search('modified: PostFields.php', $lines, true);

            self::assertIsInt($modified, implode("\n", $lines));
            $diff = \array_slice($lines, $modified + 1, 40);
            self::assertSame(['--- a/PostFields.php', '+++ b/PostFields.php'], \array_slice($diff, 0, 2));
            self::assertSame(['@@ -1,64 +1,4 @@', ' <?php', '-// drift 1'], \array_slice($diff, 2, 3));
            self::assertSame('-// drift 36', $diff[39]);
            self::assertDoesNotMatchRegularExpression('/^[-+ @\\\\]/', $lines[$modified + 41] ?? '');
            self::assertContains('missing: AcfManifest.php', $lines);
            self::assertContains('orphan: StaleFields.php', $lines);
            self::assertSame('Run: composer acf:sync (vendor/bin/tms-acf sync or wp tmswp acf sync)', $lines[\count($lines) - 1]);
        }
    }

    /**
     * docs/09 §14「…E*=2の終了コードを返し…同じ構成で2つのコマンドの出力と終了コードが同じ(tms-acfのE101の注記を
     * 除く)」。同じ投稿タイプへの2つのグループが同じ名前のフィールドを持つ(E001)と、`--strict`の有無によらずexit 2に
     * なり、2つのコマンドの出力が同じ。
     */
    public function testChecksAgreeOnGenerationErrors(): void
    {
        $root = $this->createSyncedKernel();
        self::putFile($root . '/acf-json/group_tmswp_cli_duplicate.json', self::group('group_tmswp_cli_duplicate', 'post', ['tmswp_cli_note']));
        $expected = [
            "E001: duplicate ACF field 'tmswp_cli_note' for post:post in groups group_tmswp_cli_duplicate and group_tmswp_cli_post",
            "W011: inactive ACF field group 'group_tmswp_cli_inactive' was skipped",
            'ACF bridge generation failed',
        ];

        self::assertSame($expected, self::assertChecksAgree($root, [], 2));
        self::assertSame($expected, self::assertChecksAgree($root, ['--strict'], 2));
    }

    /**
     * `wp tmswp acf check`と`tms-acf check`を同じ構成で実行し、終了コードがどちらも$expectedCodeで、出力が
     * (`tms-acf`の先頭のE101の注記を除いて)同じことを確かめ、`wp tmswp acf check`の出力の行を返す。
     *
     * @param list<string> $options
     *
     * @return list<string>
     */
    private static function assertChecksAgree(string $root, array $options, int $expectedCode): array
    {
        $wp = self::wp($root, ['tmswp', 'acf', 'check', ...$options]);
        $tmsAcf = self::tmsAcf($root, ['check', ...$options]);
        $wpLines = self::lines($wp['stdout']);
        $tmsAcfLines = self::lines($tmsAcf['stdout']);
        $context = implode(' ', $options) . "\nwp:\n" . $wp['stdout'] . $wp['stderr'] . "\ntms-acf:\n" . $tmsAcf['stdout'] . $tmsAcf['stderr'];

        self::assertSame($expectedCode, $wp['code'], $context);
        self::assertSame($expectedCode, $tmsAcf['code'], $context);
        self::assertSame('E101 (meta keys declared with #[MetaSchema]) is not checked by tms-acf because it needs the booted kernels; run wp tmswp acf check to check it', $tmsAcfLines[0] ?? null, $context);
        self::assertSame(\array_slice($tmsAcfLines, 1), $wpLines, $context);

        return $wpLines;
    }

    /**
     * postのグループ(tmswp_cli_note)と無効なグループ(W011)を持つ一時のKernelを作り、`tms-acf sync`で生成物を作る。
     */
    private function createSyncedKernel(): string
    {
        $root = $this->createKernel([
            'acf-json/group_tmswp_cli_post.json' => self::group('group_tmswp_cli_post', 'post', ['tmswp_cli_note']),
            'acf-json/group_tmswp_cli_inactive.json' => self::group('group_tmswp_cli_inactive', 'post', ['tmswp_cli_inactive'], false),
        ]);
        $sync = self::tmsAcf($root, ['sync']);
        self::assertSame(0, $sync['code'], $sync['stdout'] . $sync['stderr']);
        self::assertSame(['AcfManifest.php', 'PostFields.php'], array_keys(self::files($root . '/app/Acf')));

        return $root;
    }

    /**
     * fixtureのテーマ・プラグイン$fixtureのacf-jsonとapp/Acfを、名前空間$namespaceの一時のKernelに写し、写しの
     * 生成物(@generatedの付いたファイル)を消す。手書きのファイル(テーマのAcfStoredPost等)は残す。
     */
    private function createFixtureCopy(string $fixture, string $namespace): string
    {
        $source = self::repositoryRoot() . '/' . $fixture;
        $files = [];

        foreach (['acf-json', 'app/Acf'] as $dir) {
            foreach (self::files($source . '/' . $dir) as $name => $contents) {
                if (!str_contains($contents, self::GENERATED_MARKER)) {
                    $files["{$dir}/{$name}"] = $contents;
                }
            }
        }

        return $this->createKernel($files, $namespace);
    }

    /**
     * プラグインの形態の一時のKernel(debug。extensionsはAcfBridgeだけ)のルートを作り、$files(ルートからの相対パス
     * => 内容)を置く。tmswp-kernel.phpは、WP-CLIのプロセスのbootとtms-acfが同じものを読む。
     *
     * @param array<string, string> $files
     */
    private function createKernel(array $files, string $namespace = self::APP_NAMESPACE): string
    {
        $root = $this->createTempDirectory('acf-cli-kernel');
        self::putFile($root . '/plugin.php', "<?php\n");
        self::putFile($root . '/' . TmsAcf::KERNEL_FILE, "<?php\n\ndeclare(strict_types=1);\n\nreturn TMSWP\\Core\\Kernel\\KernelConfig::plugin(__DIR__ . '/plugin.php', __DIR__ . '/app', "
            . var_export($namespace, true) . ", true, [new TMSWP\\AcfBridge\\AcfBridge()]);\n");
        self::createDirectory($root . '/app');

        foreach ($files as $path => $contents) {
            self::createDirectory(\dirname($root . '/' . $path));
            self::putFile($root . '/' . $path, $contents);
        }

        return $root;
    }

    /**
     * $postTypeの投稿に表示する、textのフィールド$fieldNamesを持つフィールドグループのJSON。
     *
     * @param list<string> $fieldNames
     */
    private static function group(string $key, string $postType, array $fieldNames, bool $active = true): string
    {
        $fields = array_map(static fn(string $name): array => [
            'key' => 'field_' . substr($key, \strlen('group_')) . '_' . $name,
            'label' => $name,
            'name' => $name,
            'type' => 'text',
        ], $fieldNames);

        return json_encode([
            'key' => $key,
            'title' => $key,
            'fields' => $fields,
            'location' => [[['param' => 'post_type', 'operator' => '==', 'value' => $postType]]],
            'active' => $active,
        ], JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_THROW_ON_ERROR) . "\n";
    }

    /**
     * WP-CLIを、一時のKernel$root(アプリの名前空間は$namespace)を--requireでbootするプロセスで実行する。有効な
     * プラグインは$activePluginsだけにする(オプションの読み出しの上書き。DBには書かない)。
     *
     * @param list<string> $arguments
     * @param list<string> $activePlugins
     *
     * @return array{code: int, stdout: string, stderr: string}
     */
    private static function wp(string $root, array $arguments, array $activePlugins = [self::ACF_PLUGIN], string $namespace = self::APP_NAMESPACE): array
    {
        $require = $root . '/wp-cli.php';
        self::putFile($require, \sprintf(
            <<<'PHP'
                <?php

                declare(strict_types=1);

                // 統合テストのWP-CLIのプロセスだけで、有効なプラグインを決め、一時のKernelをbootする。Composerのオートローダは
                // WP-CLIのpharのオートローダより後に登録するため、muplugins_loadedで読み込む(tests/fixtures/_wp-cli.phpと同じ理由)
                WP_CLI::add_wp_hook('pre_option_active_plugins', static fn(): array => %s);
                WP_CLI::add_wp_hook('muplugins_loaded', static function (): void {
                    require %s;
                    $loader = new Composer\Autoload\ClassLoader();
                    $loader->addPsr4(%s, %s);
                    $loader->register();
                    TMSWP\Core\Kernel\Kernel::boot(TMSWP\Core\Kernel\KernelConfig::load(%s));
                }, 0);

                PHP,
            var_export($activePlugins, true),
            var_export(self::repositoryRoot() . '/vendor/autoload.php', true),
            var_export($namespace . '\\', true),
            var_export($root . '/app', true),
            var_export($root . '/' . TmsAcf::KERNEL_FILE, true),
        ));

        return self::runProcess(['wp', '--path=' . ABSPATH, '--require=' . $require, ...$arguments]);
    }

    /**
     * WordPressを起動しない`tms-acf`(packages/acf-bridge/bin/tms-acf)を、--root=$rootで実行する。
     *
     * @param list<string> $arguments
     *
     * @return array{code: int, stdout: string, stderr: string}
     */
    private static function tmsAcf(string $root, array $arguments): array
    {
        return self::runProcess([PHP_BINARY, self::repositoryRoot() . '/packages/acf-bridge/bin/tms-acf', ...$arguments, '--root=' . $root]);
    }

    /**
     * @param list<string> $command
     *
     * @return array{code: int, stdout: string, stderr: string}
     */
    private static function runProcess(array $command): array
    {
        $process = proc_open($command, [0 => ['pipe', 'r'], 1 => ['pipe', 'w'], 2 => ['pipe', 'w']], $pipes, self::repositoryRoot(), getenv());

        if (!\is_resource($process)) {
            throw new RuntimeException('cannot start ' . implode(' ', $command));
        }

        fclose($pipes[0]);
        $stdout = (string) stream_get_contents($pipes[1]);
        $stderr = (string) stream_get_contents($pipes[2]);
        fclose($pipes[1]);
        fclose($pipes[2]);

        return ['code' => proc_close($process), 'stdout' => $stdout, 'stderr' => $stderr];
    }

    /**
     * ディレクトリ$dirの直下のファイルの名前 => 内容(名前の順)。
     *
     * @return array<string, string>
     */
    private static function files(string $dir): array
    {
        $files = [];

        foreach (new FilesystemIterator($dir, FilesystemIterator::SKIP_DOTS) as $file) {
            if ($file instanceof SplFileInfo && $file->isFile()) {
                $files[$file->getFilename()] = (string) file_get_contents($file->getPathname());
            }
        }

        ksort($files, SORT_STRING);

        return $files;
    }

    /**
     * @return list<string>
     */
    private static function lines(string $output): array
    {
        return $output === '' ? [] : explode("\n", rtrim($output, "\n"));
    }

    /**
     * @return array<mixed>
     */
    private static function json(string $output): array
    {
        $decoded = json_decode($output, true, 512, JSON_THROW_ON_ERROR);
        self::assertIsArray($decoded, $output);

        return $decoded;
    }

    private static function repositoryRoot(): string
    {
        return \dirname(__DIR__, 4);
    }

    private static function createDirectory(string $dir): void
    {
        if (!is_dir($dir) && !mkdir($dir, 0775, true) && !is_dir($dir)) {
            throw new RuntimeException("cannot create {$dir}");
        }
    }

    private static function putFile(string $path, string $contents): void
    {
        if (file_put_contents($path, $contents) === false) {
            throw new RuntimeException("cannot write {$path}");
        }
    }
