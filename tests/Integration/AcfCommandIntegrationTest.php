 * 対象のKernelは、テストごとに一時ディレクトリに作るプラグインの形態のKernel(debug。AcfBridgeを登録する)である。
 * WP-CLIのプロセスは、wp-envの開発用サイト(`wp_`のテーブル)で、--requireのファイルがmuplugins_loadedでその
