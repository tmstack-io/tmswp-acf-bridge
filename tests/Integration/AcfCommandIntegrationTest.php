            'marked' => $registry->isExternallyManaged(\TMSWP\Core\Meta\ObjectType::Post, 'post', 'tmswp_cli_note'),
            'managedKeys' => class_exists($manifest) ? array_map(
                static fn(\TMSWP\AcfBridge\Manifest\ManagedKey $key): array => [$key->objectType?->value, $key->objectSubtype, $key->metaKey, $key->fieldKey, $key->groupKey],
